function slugify(romaji: string): string {
  return romaji.toLowerCase().replace(/[^a-z]/g, "");
}

function buildBase(): VocabularyEntry[] {
  const now = new Date().toISOString();
  const idByWord = new Map<string, string>();
  RAW.forEach((r) => idByWord.set(r.word, slugify(r.romaji)));

  return RAW.map((r) => {
    const id = idByWord.get(r.word)!;

    const resolve = (refs: RawRelation[] | undefined, relation: RelatedWordRef["relation"]): RelatedWordRef[] =>
      (refs ?? []).flatMap((ref) => {
        const target = RAW.find((v) => v.word === ref.word);
        if (!target) return [];
        return [
          {
            vocabularyId: idByWord.get(target.word)!,
            word: target.word,
            reading: target.reading,
            relation,
            nuance: ref.nuance,
          },
        ];
      });

    const resolveConfusing = (refs: RawConfusing[] | undefined): ConfusingWordRef[] =>
      (refs ?? []).flatMap((ref) => {
        const target = RAW.find((v) => v.word === ref.word);
        if (!target) return [];
        return [
          {
            vocabularyId: idByWord.get(target.word)!,
            word: target.word,
            reading: target.reading,
            distinction: ref.distinction,
          },
        ];
      });

    const entry: VocabularyEntry = {
      id,
      word: r.word,
      reading: r.reading,
      hiragana: r.reading,
      romaji: r.romaji,
      meaningEn: r.meaningEn,
      meaningVi: r.meaningVi,
      definitionJa: r.definitionJa,
      partOfSpeech: r.pos,
      jlptLevel: "N1",
      frequencyScore: r.freq,
      difficulty: r.diff,
      topics: r.topics,
      tags: r.tags,
      kanji: r.kanji,
      examples: r.examples.map((ex, i) => ({
        id: `${id}-ex${i + 1}`,
        japanese: ex.jp,
        translationEn: ex.en,
        translationVi: ex.vi,
        register: ex.register,
      })),
      collocations: r.collocations.map((c, i) => ({
        id: `${id}-col${i + 1}`,
        phrase: c.phrase,
        translationEn: c.en,
      })),
      synonyms: resolve(r.synonyms, "synonym"),
      antonyms: resolve(r.antonyms, "antonym"),
      confusingWords: resolveConfusing(r.confusing),
      relatedWords: resolve(r.related, "related"),
      createdAt: now,
      updatedAt: now,
    };
    return entry;
  });
}

export const VOCABULARY: VocabularyEntry[] = buildBase();

export const VOCABULARY_BY_ID: Map<string, VocabularyEntry> = new Map(
  VOCABULARY.map((v) => [v.id, v])
);

export function getVocabularyById(id: string): VocabularyEntry | undefined {
  return VOCABULARY_BY_ID.get(id);
}

